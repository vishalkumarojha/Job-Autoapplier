/**
 * Data-access seam for Jobs.
 *
 * Screens and future services depend on this interface, never on Firestore directly.
 * Keeping it free of Firebase imports means an alternate implementation (server-backed,
 * cached, or a test double) can be introduced without touching callers.
 *
 * Deliberately omitted for now: reactive observation (`onSnapshot`). Streaming is a
 * lifecycle-bearing contract that would constrain every future implementation, so it
 * is better added once a real consumer needs it.
 */

import type { CreateJobInput, IsoDateTime, Job } from '../../domain/job';

/**
 * Fields a caller may change on an existing job.
 *
 * `id`, `schemaVersion`, `createdAt`, and `dedupeKey` are excluded:
 * - the first three are immutable identity,
 * - `dedupeKey` is derived from `company`/`role`/`jobUrl` and is recomputed by the
 *   repository whenever those change.
 */
export type JobPatch = Partial<Omit<Job, 'id' | 'schemaVersion' | 'createdAt' | 'dedupeKey'>>;

export interface ListJobsOptions {
  /** Include archived jobs. Defaults to `false`. */
  includeArchived?: boolean;
  /** Field to sort by. Defaults to `createdAt`. */
  orderBy?: 'createdAt' | 'updatedAt';
  /** Sort direction. Defaults to `desc`. */
  orderDirection?: 'asc' | 'desc';
  /** Maximum number of jobs to return. Unlimited when omitted. */
  limit?: number;
}

export interface JobsRepository {
  /** Returns the user's jobs, newest first by default. Archived jobs excluded by default. */
  listJobs(options?: ListJobsOptions): Promise<Job[]>;

  /** Returns a single job, or `null` when no document with that ID exists. */
  getJobById(jobId: string): Promise<Job | null>;

  /**
   * Creates a job under a new stable ID and returns it as stored.
   * The ID is generated by the implementation, not chosen by the caller.
   */
  createJob(input: Omit<CreateJobInput, 'id'>): Promise<Job>;

  /**
   * Applies a partial change and returns the merged result.
   * Fields absent from `patch` are preserved. `updatedAt` is always advanced.
   * Throws when no job with that ID exists.
   */
  updateJob(jobId: string, patch: JobPatch): Promise<Job>;

  /**
   * Archives a job by stamping `archivedAt`, and returns the archived job.
   * Archiving is not deletion — the document is retained. `archivedAt` is injectable
   * so callers (and tests) control the timestamp.
   * Throws when no job with that ID exists.
   */
  archiveJob(jobId: string, archivedAt?: IsoDateTime): Promise<Job>;

  /**
   * Moves a draft application into review. Requires all review preconditions.
   * Returns the updated job.
   */
  startReview(jobId: string): Promise<Job>;

  /**
   * Approves an application that is in `pending_review`.
   * Requires all review preconditions to still hold.
   * Returns the updated job with `approvalStatus: "approved"`.
   */
  approveJob(jobId: string): Promise<Job>;

  /**
   * Rejects an application that is in `pending_review`.
   * Returns the updated job with `approvalStatus: "rejected"`.
   */
  rejectJob(jobId: string): Promise<Job>;

  /**
   * Reopens an approved or rejected application, returning it to `pending_review`.
   * Requires all review preconditions to still hold.
   * Returns the updated job with `approvalStatus: "pending_review"`.
   */
  reopenJob(jobId: string): Promise<Job>;
}
